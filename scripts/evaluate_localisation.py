"""Does the model point at the tumour? Compare top-contribution patches with pathologist annotations.

  uv run --no-sync python scripts/evaluate_localisation.py --cases data/demo_cases_c16 \
      --model results/raw/cache_phikon_additive

Writes results/c16_localisation.md. Only slides with annotated tumour count (normal slides have none).
"""

import argparse
from pathlib import Path

import numpy as np
import torch

from evidencemil.explain import explain_bag
from evidencemil.pipeline import load_bundle, load_model
from evidencemil.pipeline.bundle import list_bundles
from evidencemil.pipeline.run import localisation

ROOT = Path(__file__).parents[1]


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--cases", required=True)
    ap.add_argument("--model", required=True)
    args = ap.parse_args()
    model = load_model(Path(args.model))
    rows = []
    for meta in list_bundles(Path(args.cases)):
        b = load_bundle(Path(args.cases), meta["case_id"])
        if b.reference is None:
            continue
        ex = explain_bag(model.head, torch.from_numpy(b.embeddings), model.spec.temperature)
        loc = localisation(ex.contributions, b.reference)
        if loc:
            rows.append((b.case_id, ex.probability, loc, None))

    lines = ["# CAMELYON16: do the top patches fall inside the pathologist's tumour outline?", "",
             "A patch counts as tumour when ≥ 50% of it lies inside the annotation. Chance = share of",
             "sampled patches that are tumour. Additive head (seed 0) on live Phikon features of our 20x tiling.", "",
             "| slide | P(tumour) | tumour patches | chance | precision@1 | @5 | @10 | AUROC |",
             "|---|---|---|---|---|---|---|---|"]
    for cid, p, loc, _cos in rows:
        lines.append(f"| {cid} | {p:.3f} | {loc['annotated_patches']} | {loc['chance']:.3f} | "
                     f"{loc['precision_at_1']:.2f} | {loc['precision_at_5']:.2f} | {loc['precision_at_10']:.2f} | "
                     f"{loc['auroc']:.3f} |")
    if rows:
        m = {k: np.mean([r[2][k] for r in rows]) for k in ("chance", "precision_at_5", "auroc")}
        lines += ["", f"Mean over {len(rows)} slides: precision@5 {m['precision_at_5']:.2f} "
                      f"(chance {m['chance']:.3f}), AUROC {m['auroc']:.3f}."]
    lines += ["", "Generated by `scripts/evaluate_localisation.py`."]
    (ROOT / "results/c16_localisation.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
