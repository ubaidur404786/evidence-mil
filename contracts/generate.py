"""Regenerate pydantic + TypeScript types from contracts/schemas/*.json.

Run from repo root: uv run python contracts/generate.py
"""

import shutil
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).parent
SCHEMAS = ROOT / "schemas"
PY_OUT = ROOT / "src" / "evidence_contracts" / "models.py"
TS_OUT = ROOT / "generated" / "ts"
NAMES = ["StepEvent", "Evidence", "Report"]


def generate_python() -> None:
    parts = ["# Generated by contracts/generate.py from contracts/schemas. Do not edit.\n"]
    tmp = ROOT / "_tmp_model.py"
    for i, name in enumerate(NAMES):
        subprocess.run(
            [
                sys.executable, "-m", "datamodel_code_generator",
                "--input", str(SCHEMAS / f"{name}.json"), "--input-file-type", "jsonschema",
                "--output", str(tmp), "--output-model-type", "pydantic_v2.BaseModel",
                "--disable-timestamp", "--use-double-quotes", "--target-python-version", "3.11",
                "--use-title-as-name",
            ],
            check=True,
        )
        lines = tmp.read_text(encoding="utf-8").splitlines()
        body = [ln for ln in lines if not ln.startswith("#")]
        if i > 0:  # keep imports only once
            body = [ln for ln in body if not ln.startswith(("from ", "import "))]
        parts.append(f"\n# ---- {name} ----\n" + "\n".join(body).strip() + "\n")
    tmp.unlink()
    PY_OUT.write_text("\n".join(parts), encoding="utf-8")


def generate_ts() -> None:
    TS_OUT.mkdir(parents=True, exist_ok=True)
    npx = shutil.which("npx") or "npx"
    for name in NAMES:
        subprocess.run(
            [npx, "--yes", "json-schema-to-typescript@15.0.4",
             "-i", str(SCHEMAS / f"{name}.json"), "-o", str(TS_OUT / f"{name}.ts")],
            check=True,
        )


if __name__ == "__main__":
    generate_python()
    if "--python-only" not in sys.argv:
        generate_ts()
